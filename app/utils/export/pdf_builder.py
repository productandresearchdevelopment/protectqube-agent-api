def _build_daily_recording_table(
    styles,
    daily_breakdown: List[Dict[str, Any]],
    camera_list: List[Dict[str, Any]],
    total_cam: int = 4,
    online_cam: int = 2,
):
    """
    Renders the Daily Recording Status Record table with expandable daily groups
    and individual camera channel telemetry rows (Resolution, Uptime, Downtime, Success Rate, Status).
    """
    flowables = []
    flowables.append(Paragraph("<b>Daily Recording Status Record</b>", styles["SectionHeader"]))

    if not daily_breakdown:
        flowables.append(Paragraph("<i>No daily recording records available for this period.</i>", styles["BodySmallMuted"]))
        flowables.append(Spacer(1, 6))
        return flowables

    headers = ["Date / Camera Channel", "Status", "Observation", "Uptime (Mins)", "Downtime (Mins)", "Success Rate (%)"]
    rows = [[Paragraph(f"<b>{h}</b>", styles["TableHead"]) for h in headers]]

    # Prepare base cameras
    base_cams = camera_list if camera_list else [
        {"id": str(i + 1), "name": f"Camera 0{i + 1}", "resolution": "1080P", "is_online": i < online_cam}
        for i in range(total_cam)
    ]

    total_all_obs = 0.0
    total_all_up = 0.0
    total_all_down = 0.0

    group_row_indices = []

    for r in daily_breakdown:
        day_obs = float(r.get("observation_min") or ((r.get("uptime_min", 0) + r.get("downtime_min", 0))))
        dvr_up = min(day_obs, max(0.0, float(r.get("rec_uptime_min", r.get("cpu_dvr_uptime_min", day_obs)))))
        dvr_down = max(0.0, day_obs - dvr_up)
        dvr_rate = (dvr_up / day_obs * 100.0) if day_obs > 0 else 0.0

        # Day Group Header Row
        g_idx = len(rows)
        group_row_indices.append(g_idx)

        date_hdr = f"<b>{r.get('date', '-')} ({r.get('day_name', '')})</b>"
        cams_active_badge = f"<font color='#00A862'><b>{online_cam} / {total_cam} Cams Active</b></font>"

        rows.append([
            Paragraph(date_hdr, styles["TableCellBold"]),
            Paragraph(cams_active_badge, styles["TableCellCenter"]),
            Paragraph(f"<b>{day_obs:,.1f}m</b>", styles["TableCellRight"]),
            Paragraph(f"<font color='#00A862'><b>{dvr_up:,.1f}m</b></font>", styles["TableCellRight"]),
            Paragraph(f"<font color='{'#E2445C' if dvr_down > 0 else '#64748B'}'><b>{dvr_down:,.1f}m</b></font>", styles["TableCellRight"]),
            Paragraph(f"<b>{dvr_rate:.1f}%</b>", styles["TableCellRight"]),
        ])

        # Individual Camera Sub-rows
        for c_idx, c in enumerate(base_cams, start=1):
            cam_name = c.get("name") or f"Camera 0{c_idx}"
            res = c.get("resolution") or "1080P"
            is_rec = c.get("is_online", True) and (c_idx <= online_cam)

            if is_rec:
                c_up = dvr_up
                c_down = dvr_down
                c_rate = dvr_rate
                st_html = "<font color='#00A862'><b>RECORD</b></font>"
            else:
                c_up = 0.0
                c_down = day_obs
                c_rate = 0.0
                st_html = "<font color='#E2445C'><b>NO VIDEO</b></font>"

            total_all_obs += day_obs
            total_all_up += c_up
            total_all_down += c_down

            cam_label = f"&nbsp;&nbsp;&nbsp;&bull; CH {c_idx}: {cam_name} <font color='#64748B' size=6>({res})</font>"

            rows.append([
                Paragraph(cam_label, styles["TableCell"]),
                Paragraph(st_html, styles["TableCellCenter"]),
                Paragraph(f"{day_obs:,.1f}m", styles["TableCellRight"]),
                Paragraph(f"<font color='#00A862'>{c_up:,.1f}m</font>", styles["TableCellRight"]),
                Paragraph(f"<font color='{'#E2445C' if c_down > 0 else '#64748B'}'>{c_down:,.1f}m</font>", styles["TableCellRight"]),
                Paragraph(f"{c_rate:.1f}%", styles["TableCellRight"]),
            ])

    # Overall Summary Row
    avg_rec_sr = (total_all_up / total_all_obs * 100.0) if total_all_obs > 0 else 100.0
    rows.append([
        Paragraph("<b>Total Recording Telemetry</b>", styles["TableCellBold"]),
        Paragraph("<b>Overall Fleet</b>", styles["TableCellCenter"]),
        Paragraph(f"<b>{total_all_obs:,.1f}m</b>", styles["TableCellRight"]),
        Paragraph(f"<font color='#00A862'><b>{total_all_up:,.1f}m</b></font>", styles["TableCellRight"]),
        Paragraph(f"<font color='{'#E2445C' if total_all_down > 0 else '#64748B'}'><b>{total_all_down:,.1f}m</b></font>", styles["TableCellRight"]),
        Paragraph(f"<b>{avg_rec_sr:.1f}%</b>", styles["TableCellRight"]),
    ])

    table = Table(rows, colWidths=[165, 75, 70, 70, 70, 73], repeatRows=1)
    t_styles = [
        ("BACKGROUND", (0, 0), (-1, 0), BG_HEADER),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
        ("TOPPADDING", (0, 0), (-1, -1), 2.2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.2),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#F1F5F9")),
        ("LINEABOVE", (0, -1), (-1, -1), 1.2, BG_HEADER),
    ]

    for g_i in group_row_indices:
        t_styles.append(("BACKGROUND", (0, g_i), (-1, g_i), colors.HexColor("#EFF6FF")))
        t_styles.append(("LINEABOVE", (0, g_i), (-1, g_i), 0.8, PRIMARY_COLOR))

    table.setStyle(TableStyle(t_styles))
    flowables.append(table)
    flowables.append(Spacer(1, 6))
    return flowables


