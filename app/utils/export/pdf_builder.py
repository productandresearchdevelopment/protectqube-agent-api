class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic 'Page X of Y' numbering and running header/footer."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(MUTED_COLOR)
        
        # Running Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(36, 810, "ProtectQube AIOps — Gateway Telemetry & SLA Diagnostic Report")
            self.drawRightString(A4[0] - 36, 810, datetime.now(WIB).strftime("%Y-%m-%d"))
            self.setStrokeColor(BORDER_COLOR)
            self.setLineWidth(0.5)
            self.line(36, 804, A4[0] - 36, 804)

        # Running Footer (all pages)
        self.setStrokeColor(BORDER_COLOR)
        self.setLineWidth(0.5)
        self.line(36, 40, A4[0] - 36, 40)
        self.drawString(36, 28, "Confidential — Generated by ProtectQube AIOps Telemetry Engine")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(A4[0] - 36, 28, page_str)
        self.restoreState()


def _get_base_styles():
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle("ReportTitle", fontName="Helvetica-Bold", fontSize=16, leading=20, textColor=DARK_COLOR))
    styles.add(ParagraphStyle("ReportSubtitle", fontName="Helvetica", fontSize=9, leading=12, textColor=MUTED_COLOR))
    styles.add(ParagraphStyle("SectionHeader", fontName="Helvetica-Bold", fontSize=11, leading=14, textColor=PRIMARY_COLOR, spaceBefore=8, spaceAfter=4))
    styles.add(ParagraphStyle("BodySmall", fontName="Helvetica", fontSize=8.5, leading=11, textColor=DARK_COLOR))
    styles.add(ParagraphStyle("BodySmallMuted", fontName="Helvetica", fontSize=8, leading=10, textColor=MUTED_COLOR))
    styles.add(ParagraphStyle("TableCell", fontName="Helvetica", fontSize=8, leading=10, textColor=DARK_COLOR))
    styles.add(ParagraphStyle("TableCellBold", fontName="Helvetica-Bold", fontSize=8, leading=10, textColor=DARK_COLOR))
    styles.add(ParagraphStyle("TableHead", fontName="Helvetica-Bold", fontSize=8, leading=10, textColor=colors.white, alignment=1))
    styles.add(ParagraphStyle("TableCellCenter", fontName="Helvetica", fontSize=8, leading=10, textColor=DARK_COLOR, alignment=1))
    styles.add(ParagraphStyle("TableCellRight", fontName="Helvetica", fontSize=8, leading=10, textColor=DARK_COLOR, alignment=2))
    return styles


def _build_header_flowable(title: str, subtitle: str, styles):
    flowables = []
    
    # Top branding bar
    brand_data = [
        [
            Paragraph("<b>Protect<font color='#FF7A59'>Q</font>ube AIOps</b>", ParagraphStyle("Brand", fontName="Helvetica-Bold", fontSize=12, textColor=PRIMARY_COLOR)),
            Paragraph(datetime.now(WIB).strftime("%d %b %Y %H:%M WIB"), ParagraphStyle("DateTop", fontName="Helvetica", fontSize=8, textColor=MUTED_COLOR, alignment=2)),
        ]
    ]
    brand_table = Table(brand_data, colWidths=[300, 222])
    brand_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]))
    flowables.append(brand_table)
    flowables.append(Spacer(1, 4))
    flowables.append(HRFlowable(width="100%", thickness=1.5, color=PRIMARY_COLOR, spaceBefore=2, spaceAfter=8))
    
    # Title & Subtitle
    flowables.append(Paragraph(title, styles["ReportTitle"]))
    flowables.append(Paragraph(subtitle, styles["ReportSubtitle"]))
    flowables.append(Spacer(1, 10))
    return flowables


