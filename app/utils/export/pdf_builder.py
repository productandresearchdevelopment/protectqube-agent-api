def _parse_period_days(period_str: Optional[str]) -> Tuple[int, int, int, str]:
    """Extracts start_day, end_day, total_days_in_month, month_str from period string."""
    now = datetime.now(WIB)
    start_day = 1
    end_day = now.day
    days_in_month = calendar.monthrange(now.year, now.month)[1]
    month_str = now.strftime("%b %Y")

    if not period_str:
        return start_day, end_day, days_in_month, month_str

    clean_str = period_str.replace(" to ", " - ")
    parts = [p.strip() for p in clean_str.split(" - ")]
    if len(parts) >= 2:
        for fmt in ("%d %b %Y", "%Y-%m-%d", "%d/%m/%Y"):
            try:
                s_dt = datetime.strptime(parts[0], fmt)
                e_dt = datetime.strptime(parts[1], fmt)
                start_day = s_dt.day
                end_day = e_dt.day
                days_in_month = calendar.monthrange(s_dt.year, s_dt.month)[1]
                month_str = s_dt.strftime("%b %Y")
                return start_day, end_day, days_in_month, month_str
            except Exception:
                continue

    return start_day, end_day, days_in_month, month_str


def _build_timeline_section(
    styles,
    period_str: str,
    daily_breakdown: List[Dict[str, Any]],
    track_configs: List[Dict[str, str]],
):
    """
    Renders the Daily Status Timeline as a crisp, pixel-perfect vector Drawing matching the UI:
    - Dark navy container (#0B132B) with rounded corners
    - Header with Title, Period, and Days badge
    - Legend: Online (Green), Offline (Red), Today (Blue)
    - 30-day header with centered numbers (01..30) that never wrap
    - Today circled/highlighted in blue
    - Pill tracks for Gateway and DVR / Modem / Hardware with rounded corners and gaps
    - Online = #00C875, Offline = #E2445C, Inactive/Outside = #141E33
    - Subtext at bottom: "Hover or click a date (01 - 30) to filter incident details."
    """
    start_day, end_day, days_in_month, month_str = _parse_period_days(period_str)
    now = datetime.now(WIB)
    today_day = now.day if now.strftime("%b %Y") == month_str else -1
    total_days = 30
    days_cnt = max(1, end_day - start_day + 1)

    # Map daily breakdown by day number for fast lookup
    bd_map = {int(r.get("day", 0)): r for r in daily_breakdown if r.get("day") is not None}

    W = 523.0
    num_tracks = len(track_configs)
    H = 92.0 + (num_tracks * 21.0)
    d = Drawing(W, H)

    # 1. Dark Card Background
    d.add(Rect(0, 0, W, H, fillColor=colors.HexColor("#0B132B"), strokeColor=colors.HexColor("#1E293B"), strokeWidth=0.8, rx=6, ry=6))

    # 2. Header: Title, Period, Badge
    y_hdr = H - 16
    d.add(String(14, y_hdr - 2, "Daily Status Timeline", fontName="Helvetica-Bold", fontSize=9.5, fillColor=colors.white))
    p_text = f"({period_str})"
    d.add(String(124, y_hdr - 2, p_text, fontName="Helvetica", fontSize=7.5, fillColor=colors.HexColor("#94A3B8")))

    # Badge: {days_cnt} Days
    badge_w = 44
    d.add(Rect(255, y_hdr - 5, badge_w, 13, fillColor=colors.HexColor("#1E293B"), strokeColor=None, rx=6.5, ry=6.5))
    d.add(String(277, y_hdr - 2, f"{days_cnt} Days", fontName="Helvetica-Bold", fontSize=7, fillColor=colors.HexColor("#94A3B8"), textAnchor="middle"))

    # Legend
    d.add(Circle(375, y_hdr + 1, 3.2, fillColor=colors.HexColor("#00C875"), strokeColor=None))
    d.add(String(383, y_hdr - 2, "Online", fontName="Helvetica-Bold", fontSize=7, fillColor=colors.HexColor("#CBD5E1")))

    d.add(Circle(420, y_hdr + 1, 3.2, fillColor=colors.HexColor("#E2445C"), strokeColor=None))
    d.add(String(428, y_hdr - 2, "Offline", fontName="Helvetica-Bold", fontSize=7, fillColor=colors.HexColor("#CBD5E1")))

    d.add(Circle(468, y_hdr + 1, 3.2, fillColor=colors.HexColor("#0073EA"), strokeColor=None))
    d.add(String(476, y_hdr - 2, "Today", fontName="Helvetica-Bold", fontSize=7, fillColor=colors.HexColor("#CBD5E1")))

    # Separator Line
    d.add(Rect(14, H - 26, W - 28, 0.5, fillColor=colors.HexColor("#1E293B"), strokeColor=None))

    # 3. Track Header Row
    y_track_head = H - 40
    d.add(String(14, y_track_head - 2, "TRACK", fontName="Helvetica-Bold", fontSize=7, fillColor=colors.HexColor("#64748B")))

    x_start = 72.0
    avail_w = W - x_start - 14.0
    slot_w = avail_w / total_days
    pill_w = slot_w - 3.2

    for day in range(1, total_days + 1):
        x = x_start + (day - 1) * slot_w
        day_str = f"{day:02d}"

        if day == today_day:
            d.add(Rect(x - 1.2, y_track_head - 5, pill_w + 2.4, 11, fillColor=colors.HexColor("#1E3A8A"), strokeColor=colors.HexColor("#3B82F6"), strokeWidth=0.8, rx=3, ry=3))
            d.add(String(x + pill_w / 2, y_track_head - 2, day_str, fontName="Helvetica-Bold", fontSize=6, fillColor=colors.HexColor("#60A5FA"), textAnchor="middle"))
        elif start_day <= day <= end_day:
            d.add(String(x + pill_w / 2, y_track_head - 2, day_str, fontName="Helvetica-Bold", fontSize=6, fillColor=colors.HexColor("#CBD5E1"), textAnchor="middle"))
        else:
            d.add(String(x + pill_w / 2, y_track_head - 2, day_str, fontName="Helvetica", fontSize=6, fillColor=colors.HexColor("#475569"), textAnchor="middle"))

    # 4. Pill Tracks
    pill_h = 15.0
    for t_idx, cfg in enumerate(track_configs):
        y_track = H - 63.0 - (t_idx * 20.0)
        t_name = cfg["name"]
        metric_key = cfg["key"]

        d.add(String(14, y_track + 4, t_name, fontName="Helvetica-Bold", fontSize=7.5, fillColor=colors.HexColor("#E2E8F0")))

        for day in range(1, total_days + 1):
            x = x_start + (day - 1) * slot_w

            if day < start_day or day > end_day:
                pill_c = colors.HexColor("#141E33")
            else:
                r = bd_map.get(day)
                if not r:
                    pill_c = colors.HexColor("#00C875")
                else:
                    if metric_key == "gateway":
                        up_m = r.get("uptime_min", 0)
                        down_m = r.get("downtime_min", 0)
                        is_ok = (down_m == 0 or (up_m > 0 and r.get("success_rate", 100) >= 98.0))
                    elif metric_key == "dvr":
                        rec_up = r.get("rec_uptime_min", r.get("cpu_dvr_uptime_min", 0))
                        rec_down = r.get("rec_downtime_min", r.get("cpu_dvr_downtime_min", 0))
                        is_ok = (rec_down == 0 and rec_up > 0)
                    elif metric_key == "modem":
                        cell_down = r.get("cellular_downtime_min", r.get("cpu_modem_downtime_min", 0))
                        is_ok = (cell_down == 0)
                    else:
                        down_m = r.get("downtime_min", 0)
                        is_ok = (down_m == 0)

                    pill_c = colors.HexColor("#00C875") if is_ok else colors.HexColor("#E2445C")

            d.add(Rect(x, y_track, pill_w, pill_h, fillColor=pill_c, strokeColor=None, rx=2.5, ry=2.5))

    # 5. Bottom subtle hint text
    d.add(String(14, 6, "Hover or click a date (01 - 30) to filter incident details.", fontName="Helvetica", fontSize=6, fillColor=colors.HexColor("#475569")))

    return [d, Spacer(1, 6)]


def _build_incident_table(styles, events: List[Dict[str, Any]], title: str = "Incident & Disturbance History"):
    """
    Renders incident and outage events table.
    """
    flowables = []
    ev_count = len(events)
    flowables.append(Paragraph(f"<b>{title}</b> &nbsp;<font color='#64748B' size=7>({ev_count} events recorded)</font>", styles["SectionHeader"]))

    if not events:
        empty_p = Paragraph("<i>No outage or incident disturbance recorded for this period. All operations normal.</i>", styles["BodySmallMuted"])
        flowables.append(empty_p)
        flowables.append(Spacer(1, 6))
        return flowables

    headers = ["No.", "Start Time", "End Time", "Incident Description / Disturbance", "Duration", "Status"]
    rows = [[Paragraph(f"<b>{h}</b>", styles["TableHead"]) for h in headers]]

    for idx, ev in enumerate(events[:40], start=1):
        is_active = (ev.get("end_time") in ["-", "Active", "Ongoing", "Sekarang", "Now"])
        st_color = "#E2445C" if is_active else "#00A862"
        st_text = "Active" if is_active else "Resolved"

        desc = str(ev.get("title") or ev.get("description") or ev.get("cause") or "System Disturbance")
        dur = str(ev.get("duration", "-")).replace("menit", "m").replace("jam", "h")

        rows.append([
            Paragraph(str(idx), styles["TableCellCenter"]),
            Paragraph(str(ev.get("start_time", "-")), styles["TableCell"]),
            Paragraph(str(ev.get("end_time", "-")), styles["TableCell"]),
            Paragraph(desc, styles["TableCell"]),
            Paragraph(dur, styles["TableCellCenter"]),
            Paragraph(f"<font color='{st_color}'><b>{st_text}</b></font>", styles["TableCellCenter"]),
        ])

    table = Table(rows, colWidths=[25, 78, 78, 212, 65, 65], repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BG_HEADER),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, BG_LIGHT]),
        ("TOPPADDING", (0, 0), (-1, -1), 2.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    flowables.append(table)
    flowables.append(Spacer(1, 6))
    return flowables


def _build_daily_sla_table(styles, daily_breakdown: List[Dict[str, Any]], metric_type: str = "dvr"):
    """
    Renders the Daily SLA Breakdown table with exact observation minutes,
    uptime, downtime, success rate, and SLA achievement status.
    """
    flowables = []
    title = "Daily SLA Breakdown (CPU – DVR)" if metric_type == "dvr" else \
            ("Daily SLA Breakdown (CPU – Modem & Network)" if metric_type == "cellular" else "Daily SLA Breakdown (System Health)")
    
    flowables.append(Paragraph(f"<b>{title}</b>", styles["SectionHeader"]))

    if not daily_breakdown:
        flowables.append(Paragraph("<i>No daily SLA records available for this period.</i>", styles["BodySmallMuted"]))
        flowables.append(Spacer(1, 6))
        return flowables

    headers = ["Date", "Observation", "Uptime (Mins)", "Downtime (Mins)", "Success Rate (%)", "Target SLA", "SLA Status"]
    rows = [[Paragraph(f"<b>{h}</b>", styles["TableHead"]) for h in headers]]

    total_obs = 0.0
    total_up = 0.0
    total_down = 0.0

    for r in daily_breakdown:
        obs = float(r.get("observation_min") or ((r.get("uptime_min", 0) + r.get("downtime_min", 0))))
        if metric_type == "dvr":
            up = float(r.get("cpu_dvr_uptime_min", r.get("uptime_min", obs)))
            down = float(r.get("cpu_dvr_downtime_min", r.get("downtime_min", 0)))
            sr = float(r.get("cpu_dvr_success_rate", r.get("success_rate", 100.0)))
            status = str(r.get("cpu_dvr_status_sla", r.get("sla_status", "Achieved")))
        elif metric_type == "cellular":
            up = float(r.get("cellular_uptime_min", r.get("uptime_min", obs)))
            down = float(r.get("cellular_downtime_min", r.get("downtime_min", 0)))
            sr = float(r.get("cellular_success_rate", r.get("success_rate", 100.0)))
            status = str(r.get("cellular_status_sla", r.get("sla_status", "Achieved")))
        else:
            up = float(r.get("uptime_min", obs))
            down = float(r.get("downtime_min", 0))
            sr = float(r.get("success_rate", 100.0))
            status = str(r.get("sla_status", "Achieved"))

        total_obs += obs
        total_up += up
        total_down += down

        date_str = f"{r.get('date', '-')} ({r.get('day_name', '')})"
        is_achieved = status.lower() in ["achieved", "tercapai"]
        st_color = "#00A862" if is_achieved else "#E2445C"

        rows.append([
            Paragraph(date_str, styles["TableCell"]),
            Paragraph(f"{obs:,.1f}m", styles["TableCellRight"]),
            Paragraph(f"<font color='#00A862'><b>{up:,.1f}m</b></font>", styles["TableCellRight"]),
            Paragraph(f"<font color='{'#E2445C' if down > 0 else '#64748B'}'>{down:,.1f}m</font>", styles["TableCellRight"]),
            Paragraph(f"<b>{sr:.1f}%</b>", styles["TableCellRight"]),
            Paragraph("98.0%", styles["TableCellCenter"]),
            Paragraph(f"<font color='{st_color}'><b>{status}</b></font>", styles["TableCellCenter"]),
        ])

    # Footer summary row
    avg_sr = (total_up / total_obs * 100.0) if total_obs > 0 else 100.0
    overall_status = "Achieved" if avg_sr >= 98.0 else "Not Achieved"
    st_color = "#00A862" if avg_sr >= 98.0 else "#E2445C"

