class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic 'Page X of Y' numbering and running header/footer."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(MUTED_COLOR)

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(36, 810, "ProtectQube AIOps — Gateway Telemetry & SLA Diagnostic Report")
            self.drawRightString(A4[0] - 36, 810, datetime.now(WIB).strftime("%Y-%m-%d"))
            self.setStrokeColor(BORDER_COLOR)
            self.setLineWidth(0.5)
            self.line(36, 804, A4[0] - 36, 804)

        # Running Footer (all pages)
        self.setStrokeColor(BORDER_COLOR)
        self.setLineWidth(0.5)
        self.line(36, 36, A4[0] - 36, 36)
        self.drawString(36, 24, "Confidential — Generated by ProtectQube AIOps Telemetry Engine")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(A4[0] - 36, 24, page_str)
        self.restoreState()


